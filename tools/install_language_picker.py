#!/usr/bin/env python3
"""Install the language picker and Russian sample into the verified Steam build."""

import argparse
import json
from pathlib import Path

from extract_text import pin_install, require


PROJECT = Path(__file__).resolve().parent.parent


def install(root):
    expected = json.loads((PROJECT / "text-asset-receipt.json").read_text())["sources"]
    require(pin_install(root) == expected, "Installed base scripts differ from the extraction receipt")

    screens = (root / "game/screens.rpy").read_text(encoding="utf-8-sig")
    _, found, rest = screens.partition("screen preferences():\n")
    preferences, end, _ = rest.partition("\nstyle pref_label is gui_label\n")
    require(found and end, "Could not isolate the Preferences screen")
    anchor = "        vbox:\n\n            hbox:\n"
    require(preferences.count(anchor) == 1, "Unexpected Preferences screen structure")
    preferences = preferences.replace(
        anchor, "        vbox:\n\n            hbox:\n                use vnrevival_language_picker\n"
    )
    picker = (PROJECT / "localization/language_picker.rpy").read_text(encoding="utf-8")
    override = (
        "# Generated by tools/install_language_picker.py.\n"
        "init offset = 10\n\n"
        f"{picker.rstrip()}\n\n{found}{preferences.rstrip()}\n"
    )
    files = {
        root / "game/vnrevival_protogen_preferences.rpy": override.encode("utf-8"),
        root / "game/tl/russian/vnrevival_protogen_sample.rpy": (
            PROJECT / "localization/russian_sample.rpy"
        ).read_bytes(),
    }

    pending = {}
    for path, data in files.items():
        if path.is_file() and path.read_bytes() == data:
            continue
        require(
            not path.exists() and not path.with_suffix(".rpyc").exists(),
            f"Refusing to overwrite a different add-on at {path}",
        )
        pending[path] = data

    created = []
    try:
        for path, data in pending.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("xb") as target:
                created.append(path)
                target.write(data)
    except OSError:
        for path in reversed(created):
            path.unlink()
        raise

    for path in files:
        print(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("steam_install", type=Path, help="My Furry Protogen installation directory")
    args = parser.parse_args()
    try:
        install(args.steam_install.resolve())
    except (OSError, ValueError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
